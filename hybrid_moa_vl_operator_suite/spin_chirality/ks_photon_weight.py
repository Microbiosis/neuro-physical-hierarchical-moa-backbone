# 3. 谱权重与动量分解
# ==============================================================================
def spectral_stats(m) -> dict:
    """|m_x|² 的分布统计：W、每格权重、参与比、峰占比、中段占比。

    `PR` = (Σ|m|²)²/(N Σ|m|⁴)：铺满整条链 → O(1)，只占一格 → 1/N。
    `mid_frac` = x ∈ [N/4, 3N/4) 的权重占比：铺满 → 0.5，聚在接缝 → →0。
    """
    a = np.abs(np.asarray(m, dtype=complex)) ** 2
    N = a.size
    W = float(a.sum())
    lo, hi = N // 4, max(N // 4 + 1, (3 * N) // 4)
    return {"N": int(N), "W": W, "W_per_N": W / N, "W_per_N3": W / N ** 3,
            "PR": float(W * W / ((a * a).sum() * N)) if W > 0 else float("nan"),
            "max_frac": float(a.max() / W) if W > 0 else float("nan"),
            "mid_frac": float(a[lo:hi].sum() / W) if W > 0 else float("nan")}


def momentum_profile(m, nk: int = 8):
    """连续 k 上的傅里叶变换：m̃(k) = N^{−1/2} Σ_x m_x e^{−ikx}，k ∈ [0, 2π) 取 nk·N 点。

    Parseval：Σ_x |m_x|² = (1/nk)Σ_k |m̃(k)|²（nk = 1 时就是标准的正交 DFT）。
    """
    m = np.asarray(m, dtype=complex)
    N = m.size
    k = 2.0 * _PI * np.arange(nk * N) / (nk * N)
    f = np.exp(-1j * np.outer(k, np.arange(N))) @ m / np.sqrt(N)
    return k, f


def momentum_concentration(m) -> dict:
    """k 空间的集中度：峰位、峰占比、PRk（1 = 全在一个 k 上，1/N = 铺平）。

    "铺平"就是实空间的 δ 函数（局域物体）；"单峰"就是实空间的平面波（离域）。
    `at(k0)` 给出任意 k0 处的 |m̃(k0)|²/W，用来问"φ/N 处有没有峰"。
    """
    m = np.asarray(m, dtype=complex)
    N = m.size
    W = float((np.abs(m) ** 2).sum())
    k = 2.0 * _PI * np.arange(8 * N) / (8 * N)
    f = np.exp(-1j * np.outer(k, np.arange(N))) @ m / np.sqrt(N)
    w = np.abs(f) ** 2
    grid = np.fft.fft(m) / np.sqrt(N)
    wg = np.abs(grid) ** 2
    j = int(np.argmax(w))
    return {"k_peak": float(k[j]), "w_peak": float(w[j]),
            "peak_frac": float(w[j] / W) if W > 0 else float("nan"),
            "top_frac": float(wg.max() / W) if W > 0 else float("nan"),
            "PRk": float(W * W / (N * (wg ** 2).sum())) if W > 0 else float("nan"),
            "W": W}


def weight_at(m, k0: float) -> float:
    """在给定 k0 处的 |m̃(k0)|²（不归一，便于和峰高直接比）。"""
    m = np.asarray(m, dtype=complex)
    x = np.arange(m.size)
    return float(abs(np.exp(-1j * k0 * x) @ m) ** 2 / m.size)


def fraction_at(m, k0: float) -> float:
    """在给定 k0 处的权重占全 k 权重的比例：|m̃(k0)|²/W。"""
    W = float((np.abs(np.asarray(m, dtype=complex)) ** 2).sum())
    return weight_at(m, k0) / W if W > 0 else float("nan")


