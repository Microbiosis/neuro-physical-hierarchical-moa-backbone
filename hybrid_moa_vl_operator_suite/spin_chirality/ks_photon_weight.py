def _ed_module():
    from . import ks_ed
    return ks_ed


def _dense_reference(N, g, m=0.0, t=0.5, phi=0.0):
    """稠密 ED 侧的 H、E_x、j_x（只在自检里用）。返回 (H, masks, E[N,dim,dim], j[N,dim,dim])。

    这三样与 MPS 侧用的是**同一套约定**：E_x = Σ_{y≤x}ρ_y（接缝链接 = 总电荷 0）、
    j_x = i t (χ†_xU_xχ_{x+1} − h.c.)、跨切口那条带 e^{iφ} 与 JW 弦。自检 ① 用
    i[H,E_x] = j_{N−1} − j_x 把三者一起钉死。
    """
    ked = _ed_module()
    Emax = N + 2
    H, masks, _Es = ked.basis_and_hamiltonian(N, g, m, t=t, Emax=Emax, phi=phi)
    index = {mk: i for i, mk in enumerate(masks)}
    dim = len(masks)
    zph = np.exp(1j * phi) if phi else 1.0
    E = np.zeros((N, dim, dim), dtype=float)
    A = np.zeros((N, dim, dim), dtype=complex)
    for i, mk in enumerate(masks):
        r = np.empty(N)
        for x in range(N):
            r[x] = ((mk >> x) & 1) - 0.5 * (1.0 - ((-1.0) ** x))
        E[:, i, i] = np.cumsum(r)
        for x in range(N):
            y = (x + 1) % N
            if ((mk >> y) & 1) and not ((mk >> x) & 1):
                new = mk ^ (1 << x) ^ (1 << y)
                j = index.get(new)
                if j is None:
                    continue
                lo, hi = (x, y) if x < y else (y, x)
                between = bin(mk & (((1 << hi) - 1) ^ ((1 << (lo + 1)) - 1))).count("1")
                sign = -1.0 if between % 2 else 1.0
                if x == N - 1:
                    sign = sign * zph
                A[x, i, j] += sign
    j = 1j * t * (A - np.conj(np.transpose(A, (0, 2, 1))))
    return H, masks, E, j


def _dense_amps(N, g, m=0.0, t=0.5, phi=0.0):
    """稠密 ED 的 ⟨1|E_x|0⟩、⟨1|ρ_x|0⟩、⟨1|j_x|0⟩ 与 gap（对照 MPS 侧）。"""
    H, masks, E, j = _dense_reference(N, g, m, t, phi)
    w, v = np.linalg.eigh(H)
    v0, v1 = v[:, 0], v[:, 1]
    E_t = np.array([np.vdot(v1, E[x] @ v0) for x in range(N)])
    j_t = np.array([np.vdot(v1, j[x] @ v0) for x in range(N)])
    rho_t = np.diff(np.concatenate([[0.0], E_t]))
    return {"gap": float(w[1] - w[0]), "E": E_t, "j": j_t, "rho": rho_t,
            "v": v, "masks": masks, "H": H, "Eops": E, "jops": j}


def _mps_to_dense(A):
    """MPS → 稠密矢，位序与 `ks_ed` / `mpo_dense` 一致（0 号格点 = 最低位）。"""
    N = len(A)
    v = np.ones((1, 1), dtype=complex)
    for a in A:
        v = np.tensordot(v, a, axes=([1], [0])).reshape(-1, a.shape[2])
    v = v.ravel().reshape((2,) * N)
    return np.transpose(v, list(range(N))[::-1]).ravel()


def _random_full_mps(N, seed=0):
    """随机满键维 MPS（χ 取满 ⇒ 精确态）+ 它的稠密矢。"""
    rng = np.random.default_rng(seed)
    A = []
    for i in range(N):
        l, r = 2 ** min(i, N - i), 2 ** min(i + 1, N - i - 1)
        A.append(rng.normal(size=(l, 2, r)) + 1j * rng.normal(size=(l, 2, r)))
    v = _mps_to_dense(A)
    nrm = float(np.linalg.norm(v))
    A[0] = A[0] / nrm
    return A, v / nrm


def _apply_site(v, N, x, O):
    r = v.reshape(-1, 2, 2 ** x)
    return np.einsum('aib,ij->ajb', r, O).reshape(-1)


def _apply_link(v, N, x, O):
    r = v.reshape(-1, 2, 2, 2 ** x)
    return np.einsum('aijb,ijkl->aklb', r, O).reshape(-1)


