"""电场矩阵元、谱权重与动量分解：最低激发里"光子成分"有多大（P38）。

问题
----
P36/P37 把 `gap/e` 与 `gap(φ)` 都量出来了，结论是"主导激发是离域粒子型，但既不是
自由光子、也不是纯弦"。那条结论是**间接**的（从能谱推断）。本项直接量**算符**：

  ⟨1|E_x|0⟩   电场算符在基态与最低激发之间的矩阵元 —— 规范场量子与电场耦合的
              定义性判据（光子作为规范场量子必须有非零耦合；弦态是两端的定域物体，
              它的 E 矩阵元集中在两端/被切口的接缝）；
  ⟨1|ρ_x|0⟩   = ⟨1|E_x|0⟩ − ⟨1|E_{x−1}|0⟩，即 ∂_x⟨1|E_x|0⟩。这是**与切口约定无关**的
              那一半信息（E 在环上只能定到相差一个常数，见下）；
  ⟨1|j_x|0⟩   电流矩阵元，用恒等式与上两者绑定（见"恒等式"）。

三个约定，先说清楚
------------------
① **电场只定到相差一个常数**。环上高斯定律 `E_x − E_{x−1} = ρ_x` 把 E 逐点钉住、
   整体常数不定；本包（与 `ks_ed` 一致）取 `E_x = Σ_{y≤x} ρ_y`，等价于"跨切口那条
   链接上的场 = 总电荷 Q = 0"。于是 **⟨1|E_{N−1}|0⟩ ≡ ⟨1|Q|0⟩ = 0** 是恒等式，任何
   沿 x 的"分布"都必然在接缝处归零。`W_E = Σ_x |⟨1|E_x|0⟩|²` 因此带上这个约定，
   它随 N 的增长里混着"坡道"（cumsum）的因子；所以另报三个约定无关的量：
   `W_ρ = Σ_x |⟨1|ρ_x|0⟩|²`（逐点、无 cumsum）、两个参与比 `PR_E`、`PR_ρ`
   （= (Σ|m|²)²/(N Σ|m|⁴)，1 = 铺满整条链、→1/N = 只占一格），以及中段权重占比
   `mid_frac`（x ∈ [N/4, 3N/4] 的权重占比；铺满 → 0.5，聚在接缝 → 0）。
② **电流的定义**。取
       j_x ≡ +i t (χ†_x U_x χ_{x+1} − χ†_{x+1} U_x† χ_x)，      x = 0..N−1
   （x = N−1 是跨切口那条，U 带相位 e^{iφ}，中间要穿 JW 弦）。它满足的**精确**
   算符恒等式（稠密 ED 逐元素验证到 1e-16，见自检 ①）是

       i[H, E_x] = j_{N−1} − j_x        ⟺        ∂_t E_x = j_{N−1} − j_x

   也就是"∂_tE = −j"（差一个整体符号是我们对 j 的取向，见自检 ①）加上一个接缝常数
   j_{N−1}。于是任意一对本征态之间

       ⟨1|j_x|0⟩ = ⟨1|j_{N−1}|0⟩ − i·gap·⟨1|E_x|0⟩        （gap = E1 − E0）

   右边对 x 必须是**同一个常数**。这条式子本项既用来算 j（不必单独造 E 的 MPO），
   也当成整套机器的自检：`R_x ≡ ⟨1|j_x|0⟩ + i·gap·⟨1|E_x|0⟩` 的 x 散布就是
   "|1⟩ 到底是不是本征态 + 跃迁振幅有没有写对"的一把尺子（ED 上 1.7e-15）。
   因子关系：|⟨1|j_x|0⟩| 与 gap·|⟨1|E_x|0⟩| 同量级，两者只差 i·gap 与接缝常数。
③ 振幅一律按 `⟨ψ1|O|ψ0⟩` 归一（两端 MPS 各自归一），复数（φ ≠ 0）照常。

复 MPO 的腿序（做 φ ≠ 0 必须先知道的一件事）
--------------------------------------------
已有的 `ks_mps.energy` / `apply_heff` 把 MPO 的物理腿读成 (ket,bra)，而 `mpo_dense`
读成 (bra,ket)。对**实** MPO（φ = 0）两者逐位相同（H 实对称），所以 P36/P37 的 φ=0
结果不受影响；对**复** MPO（φ ≠ 0）两者差一次转置，等价于把 H 换成 Hᵀ = H*。谱不变
（Hᵀ 与 H 同谱），所以 P37 的 gap(φ) 与二次系数 b 也照旧；但**态**变了：变分最优点
是 conj(ψ)。实测（N=8/10/12，x=0.4，φ=π/2）：未共轭的 MPS 与 ED 本征矢的重叠只有
|⟨ψ_ED|ψ_MPS⟩| = 0.72/0.33（基态/激发态），而 |⟨ψ_ED|conj ψ_MPS⟩| = 1.000000
（4e-9）；逐构型模长相同、相位不同，正是"整体共轭"的指纹。
`dmrg_state_pair` 因此在 φ ≠ 0 时把两个 MPS 逐元素共轭回来（`conj=True`），自检 ⑦ 把
这条性质本身也钉在残差里。不这么做的后果很直接：`R_x` 的 x 散布会从 1e-7 跳到 2.2
（j 与 E 的相对相位是物理的），谱权重里那些只看 |振幅| 的量却照样"看起来对"。

方法（全部复用已有的 DMRG 引擎）
--------------------------------
`ks_mps.dmrg_gap` 给出 |0⟩、|1⟩（正交 DMRG）与 gap；本模块只加三个**跃迁振幅**收缩：
单格点 `trans_amp_site`、两格点链接 `trans_amp_link`、带 JW 弦的整条 MPO
`trans_amp_mpo`。三者都在 N=6/8 的**精确**随机 MPS（χ 取满）上与稠密 vec 对到
1e-16（自检 ②），再在 N=8/10 上与稠密 ED 的本征矢对到 1e-7（自检 ③）。

"光子成分"怎么量化
------------------
(a) 形状：`PR`、`mid_frac`、逐点分布（表 `EFIELD_PROFILE_SCAN`）；
(b) 动量：`momentum_profile` 在连续 k 上做傅里叶（Parseval 归一，Σ_x|m|² =
    (1/N)Σ_k|m̃|²），报峰位、峰占比、`PRk`（k 空间集中度）；
(c) **求和规则**：`Σ_n |⟨n|E_x|0⟩|² = ⟨0|δE_x²|0⟩`（完备性）。所以

       f₁ ≡ Σ_x |⟨1|E_x|0⟩|² / Σ_x ⟨0|δE_x²|0⟩

    就是"电场算符的谱权重里，最低那一根本征态占了多少"。自由单模场（纯光子）把
    全部权重放在 |1⟩ 上（f₁ = 1）；谱权重摊到连续谱上则 f₁ ≪ 1。
    分母用 E_x² 的 3 通道 MPO 直接算（`efield_square_mpo`），并与 P37 的
    `CORR_SCAN` 里的 C(0) = ⟨δE_x²⟩ 交叉验证（两条独立路径，见自检 ⑦）。

实测结论（N = 16/20、χ = 64、sweeps = 10；表在下面，复现见 `ks_photon_weight_scan.py`）
------------------------------------------------------------------------------------
**(1) ⟨1|E_x|0⟩ 的形状**：非零、既不均匀也不"两端定域"。|⟨1|E_x|0⟩| 沿链在 0.046–0.156
之间（x=0.4、N=20、φ=0 的逐点是 0.0826, 0.0584, 0.1094, 0.0946, 0.1273, 0.1182, 0.1377,
0.1317, 0.1425, 0.1360, 0.1425, …；接缝处 E_{N−1} = Q ≡ 0 是恒等式，所以每行末位必为 0）；|⟨1|ρ_x|0⟩| = |∂_x⟨1|E_x|0⟩|
在接缝两侧最大、向中间指数衰减：x=0.4、N=20 的偶格包络是 0.0826, 0.0510, 0.0328, 0.0195,
0.0108（相邻比 1.62/1.55/1.68/1.81 ⇒ 衰减长度 ≈ 4.0 格）；x=1.0、N=20 是 0.0482, 0.0281,
0.0154, 0.0081, 0.0026（比 1.72/1.83/1.89/3.16 ⇒ ≈ 2.2 格）。**两个 x 都被接缝钉住**，
所以"定域 ⇒ 弦态 / 离域 ⇒ 光子"这条判据在 N ≤ 20 上无法二分（见 (5)）。

**(2) 谱权重**：W_E = Σ_x|⟨1|E_x|0⟩|² = 0.177–0.287；W_ρ = Σ_x|⟨1|ρ_x|0⟩|² = 0.0073–0.090。
x=0.4 的 W_ρ 是 x=1.0 的 2.44 / 5.06 / 3.29 / 5.25 倍（N=16,20 × φ=0,π2 四点全部）；
每格权重 W_ρ/N 在 N=16→20 上 x=0.4 掉到 0.835/0.648、x=1.0 掉到 0.496/0.460 ⇒ 两者都
随 N 收缩，对照点快一倍（定域物体该按 1/N 掉，x=1.0 更接近这个行为）。

**(3) 动量分解**：|ρ̃_k| 在 k = π（= 2k_F）成**单峰**，峰占比 x=0.4 为 0.554–0.821、
x=1.0 为 0.163–0.216（差 2.6–5 倍）。**±φ/N 处没有峰**：x=0.4、φ=π/2 时
f(±φ/N)/f(峰) = 0.031 / 0.050，f(π)/f(峰) = 1.000；峰位在 φ=0 与 φ=π/2 之间**不动**
（都在 π，偏差 0）。⇒ 最低激发是**中性**的（总动量 0），磁通只移动内部动量——正是
P37 在 gap(φ) 上量到的那件事。"峰在 −φ/N"这条判据**不成立**，而且不成立得对：φ/N 是
电荷 ±1 的动量，中性激发不该有它。

**(4) 光子成分**：f₁ = Σ_x|⟨1|E_x|0⟩|² / Σ_x⟨0|δE_x²|0⟩ = 0.048–0.070（x=0.4）、
0.077–0.119（x=1.0 对照点，反而更大）。自由单模场是 f₁ = 1；实测 5–12% 说明最低那一根
本征态只拿走电场**非弹性**谱权重的百分之几，其余在更高激发里。求和规则本身在稠密 ED
上验到 2.8e-16；分母 ⟨0|δE_x²|0⟩ 与 P37 用完全不同的路径（全部 N² 个 ⟨ρ_aρ_b⟩）算的
C(0) 差 0.3%/0.5%（N=16/20 对 N=24 的 0.196748）。

**(5) 负结果（诚实条款）**
· "离域 vs 定域"这条判据在 N ≤ 20 上无效：两个 x 的 ρ 矩阵元都定域在接缝附近（|E_x|
  平坦但 |ρ_x| 都衰减），因为环上的 CDW 在接缝处有缺陷（P37 量到 ⟨ρ_x⟩ 从接缝的 ±0.36
  涨到中间的 ±0.44），缺陷把振幅钉住了。要把它和物理定域分开需要 N ≫ ξ 并让 ξ 与缺陷
  解耦，按 P37 的本底估计要 N ≈ 60–80——本机 N=24 单点已 12 min，**时间预算不允许**
  （降规模到 N ≤ 20 是这次的实际选择）。
· "峰在 −φ/N"判据不成立（见 (3)），原因是物理的：激发中性，φ 只进内部动量。
· 因此判据换成可复现的一组量：k 峰在 π + 峰占比 + f(±φ/N)/f(峰) 很小 + W_ρ/W_ρ(对照)
  ≥ 1.8 + PR_ρ 比对照点大 ≥ 10% + f₁ ∈ [0.03, 0.10]（都在 `check_ks_photon_weight` 里）。
"""
