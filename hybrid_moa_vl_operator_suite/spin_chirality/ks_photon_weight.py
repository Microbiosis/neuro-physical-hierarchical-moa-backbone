# 4. 一次算完一个点（含求和规则）
# ==============================================================================
def efield_variance(A0, N=None):
    """⟨0|δE_x²|0⟩ 逐点 = ⟨0|E_x²|0⟩ − |⟨0|E_x|0⟩|²（求和规则的分母）。O(N²Dχ³)。"""
    N = len(A0) if N is None else int(N)
    nrm = _mps_norm(A0)
    rho = trans_amp_site(A0, A0, [_mps._rho_op(x) for x in range(N)]) / nrm
    Em = np.cumsum(rho).real
    E2 = np.array([float(np.real(trans_amp_mpo(A0, efield_square_mpo(N, x), A0) / nrm))
                   for x in range(N)])
    return E2 - Em * Em


def dmrg_state_pair(N, x, phi=0.0, chi=96, sweeps=12, seed=5, m=0.0, t=0.5):
    """跑一次 `ks_mps.dmrg_gap` 并返回 {A0, A1, gap, E0, E1, gap_over_e, e, conj}。

    **φ ≠ 0 时返回的 MPS 是真态的复共轭**（见模块文档"复 MPO 的腿序"一节）：已有的
    `ks_mps.energy` / `apply_heff` 用 (ket,bra) 的物理腿序收缩，`mpo_dense` 用 (bra,ket)；
    实 MPO（φ=0）下两者无差别，复 MPO 下等价于把 H 换成 Hᵀ = H*，于是变分最优点是
    conj(ψ)。谱（E0/E1/gap）不变，所以 P37 的能量结论不受影响；但态依赖的观测量必须
    先共轭回来。这里就地把 A0/A1 共轭，`conj=True` 记下做过这件事。
    """
    r = _mps.dmrg_gap(N, x, m, chi=chi, sweeps=sweeps, seed=seed, phi=phi, t=t)
    A0, A1 = r["A"], r["A1"]
    conj = bool(phi)
    if conj:
        A0 = [np.conj(a) for a in A0]
        A1 = [np.conj(a) for a in A1]
    return {"A0": A0, "A1": A1, "gap": float(r["gap"]), "E0": float(r["E0"]),
            "E1": float(r["E1"]), "gap_over_e": float(r["gap_over_e"]),
            "e": float(r["e"]), "conj": conj, "chi": int(r["bond"])}


def photon_weight(N, x, phi=0.0, chi=96, sweeps=12, seed=5, m=0.0, sum_rule=True,
                  t=0.5) -> dict:
    """一个 (N, x, φ) 点的全部量：三个矩阵元、谱权重、k 分布、求和规则、EOM 残差。

    返回字典的键：
      `E`/`rho`/`j`       —— ⟨1|E_x|0⟩、⟨1|ρ_x|0⟩、⟨1|j_x|0⟩（含跨切口那条）
      `gap`/`gap_over_e`  —— 能隙与 gap/e
      `W_E`/`W_rho`       —— Σ_x|⟨1|E_x|0⟩|²、Σ_x|⟨1|ρ_x|0⟩|²
      `PR_E`/`PR_rho`     —— 参与比（铺满链 → O(1)，聚在一处 → →1/N）
      `mid_E`/`mid_rho`   —— 中段 [N/4,3N/4) 的权重占比（铺满 → 0.5）
      `k_rho`/`k_E`       —— `momentum_concentration` 的输出
      `eom_rel`           —— R_x = ⟨1|j_x|0⟩ + i·gap·⟨1|E_x|0⟩ 的 x 散布（相对）
      `f1`                —— Σ_x|⟨1|E_x|0⟩|² / Σ_x⟨0|δE_x²|0⟩（最低态占电场谱权重的比例）
      `var_E`             —— ⟨0|δE_x²|0⟩ 逐点（sum_rule=False 时为 None）
    """
    sp = dmrg_state_pair(N, x, phi=phi, chi=chi, sweeps=sweeps, seed=seed, m=m, t=t)
    fe = field_matrix_elements(sp["A0"], sp["A1"], sp["gap"], t=t, phi=phi)
    eom = eom_residual(fe, sp["gap"])
    sE, sr = spectral_stats(fe["E"]), spectral_stats(fe["rho"])
    out = {"N": int(N), "x": float(x), "phi": float(phi), "gap": sp["gap"],
           "gap_over_e": sp["gap_over_e"], "e": sp["e"], "conj": sp["conj"],
           "E": fe["E"], "rho": fe["rho"], "j": fe["j"], "echo": fe["echo"],
           "W_E": sE["W"], "W_rho": sr["W"],
           "W_E_per_N": sE["W_per_N"], "W_rho_per_N": sr["W_per_N"],
           "PR_E": sE["PR"], "PR_rho": sr["PR"],
           "mid_E": sE["mid_frac"], "mid_rho": sr["mid_frac"],
           "max_frac_E": sE["max_frac"], "max_frac_rho": sr["max_frac"],
           "k_rho": momentum_concentration(fe["rho"]),
           "k_E": momentum_concentration(fe["E"]),
           "eom_rel": eom["rel"], "eom_spread": eom["spread"],
           "f1": float("nan"), "var_E": None}
    if sum_rule:
        var = efield_variance(sp["A0"], N)
        out["var_E"] = var
        out["var_mean"] = float(np.mean(var))
        out["f1"] = float(sE["W"] / var.sum()) if var.sum() > 0 else float("nan")
    return out


