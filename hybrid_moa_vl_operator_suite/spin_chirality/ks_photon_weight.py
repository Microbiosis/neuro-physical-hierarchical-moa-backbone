# 1. 跃迁振幅：⟨ψ1|O|ψ0⟩（单格点 / 两格点 / 整条 MPO）
# ==============================================================================
def _left_env(A1, A0):
    """L[i][a1,a0] = ⟨ψ1|_{<i} ψ0⟩_{<i}（a1/a0 是 A1[i]/A0[i] 的左脚）。"""
    N = len(A1)
    L = [None] * (N + 1)
    L[0] = np.ones((1, 1), dtype=complex)
    for i in range(N):
        L[i + 1] = np.einsum('ab,asf,bsg->fg', L[i], A1[i].conj(), A0[i])
    return L


def _right_env(A1, A0):
    """R[i][a1,a0] = ⟨ψ1|_{≥i} ψ0⟩_{≥i}（右脚）。"""
    N = len(A1)
    R = [None] * (N + 1)
    R[N] = np.ones((1, 1), dtype=complex)
    for i in range(N - 1, -1, -1):
        R[i] = np.einsum('asf,bsg,fg->ab', A1[i].conj(), A0[i], R[i + 1])
    return R


def _mps_norm(A):
    """⟨ψ|ψ⟩（由环境精确给出，不靠 A 的规范化程度）。"""
    v = np.ones((1, 1), dtype=complex)
    for a in A:
        v = np.einsum('ab,asf,bsg->fg', v, np.conj(a), a)
    return float(np.real(v[0, 0]))


def trans_amp_site(A1, A0, ops):
    """⟨ψ1| O_x |ψ0⟩ 逐点，ops[x] 是 2×2。O(Nχ³)。

    分步收缩而不用一个多算符 `einsum`：后者让 numpy 现场选路径，实测在 χ=64、N=16 上
    会挑出 20–30 s 的中间量（分步是 0.05 s），代价差三个数量级。
    """
    N = len(A1)
    L, R = _left_env(A1, A0), _right_env(A1, A0)
    out = np.zeros(N, dtype=complex)
    for i in range(N):
        X = np.einsum('ab,asf->bsf', L[i], A1[i].conj())               # (a0,s,f)
        Y = np.einsum('bsf,btg->stfg', X, A0[i])                       # (s,t,f,g)
        out[i] = np.einsum('stfg,st,fg->', Y, ops[i], R[i + 1])
    return out


def trans_amp_link(A1, A0, ops):
    """⟨ψ1| L_x |ψ0⟩，L_x 作用在 (x, x+1)；ops[x] 形状 (2,2,2,2) = ⟨s,t|L|u,v⟩。

    返回长度 N−1（x = 0..N−2）；跨切口那条要用 `seam_current_mpo` + `trans_amp_mpo`。
    """
    N = len(A1)
    L, R = _left_env(A1, A0), _right_env(A1, A0)
    out = np.zeros(max(N - 1, 0), dtype=complex)
    for i in range(N - 1):
        X = np.einsum('ab,asf->bsf', L[i], A1[i].conj())               # (a0,s,f)
        Y = np.einsum('bsf,bug->sfug', X, A0[i])                       # (s,f,u,g)
        Z = np.einsum('sfug,stuv->fgtv', Y, ops[i])                    # (f,g,t,v)
        Z2 = np.einsum('fgtv,fth->ghtv', Z, A1[i + 1].conj())          # (g,h,t,v)
        Z3 = np.einsum('ghtv,gvw->htw', Z2, A0[i + 1])                 # (h,t,v,w)
        out[i] = np.einsum('htw,hw->', Z3, R[i + 2])
    return out


def trans_amp_mpo(A1, Ws, A0):
    """⟨ψ1|M|ψ0⟩，M 由 MPO `Ws`（W[a,s,t,b]）给出。O(NDχ³)。"""
    N = len(A1)
    D = Ws[0].shape[0]
    E = np.zeros((1, 1, D), dtype=complex)
    E[0, 0, 0] = 1.0
    for x in range(N):
        T = np.einsum('ija,isf->jasf', E, A1[x].conj())                # (ψ0 键, 通道, s, f)
        T = np.einsum('jasf,astb->jftb', T, Ws[x])
        E = np.einsum('jftb,jtg->fgb', T, A0[x])
    return E[0, 0, -1]


def link_current_op(t: float = 0.5):
    """链接电流 j_x = i t (S⁺ₓS⁻ₓ₊₁ − S⁻ₓS⁺ₓ₊₁) 的 2×2×2×2 张量（离接缝的链接）。

    与 `ks_mps.mpo_ks` 的通道 2/3 同一个约定：跳迁项是 −t(S⁺ₓS⁻ₓ₊₁ + h.c.)，
    所以 χ†_xχ_{x+1} ↔ S⁺ₓS⁻ₓ₊₁。整体符号由自检 ① 的 [H,E] 恒等式钉死。
    """
    sp, sm = _mps._SP, _mps._SM
    return 1j * t * (np.einsum('st,uv->stuv', sp, sm) - np.einsum('st,uv->stuv', sm, sp))


def seam_current_mpo(N: int, t: float = 0.5, phi: float = 0.0):
    """跨切口那条链接的电流 j_{N−1}（要穿 JW 弦 Π_{0<y<N−1} (−σ^z_y)）的 4 通道 MPO。

    通道 0 = I（直通），1 = 第一支已开（e^{iφ} χ†_{N−1}χ_0），2 = 第二支已开（h.c.），
    3 = 收尾。φ = 0 时数值仍是实数，但为了少一个 dtype 分支这里固定用复数。
    """
    zph = np.exp(1j * phi) if phi else 1.0
    out = []
    for x in range(N):
        W = np.zeros((4, 2, 2, 4), dtype=complex)
        W[0, :, :, 0] += _mps._I2
        W[3, :, :, 3] += _mps._I2
        if x == 0:
            W[0, :, :, 1] += 1j * t * zph * _mps._SM
            W[0, :, :, 2] += -1j * t * np.conj(zph) * _mps._SP
        elif x < N - 1:
            W[1, :, :, 1] += _mps._ZN
            W[2, :, :, 2] += _mps._ZN
        else:
            W[1, :, :, 3] += _mps._SP
            W[2, :, :, 3] += _mps._SM
        out.append(W)
    return out


def efield_square_mpo(N: int, xcut: int):
    """E_x² = (Σ_{y≤xcut}ρ_y)² 的 3 通道 MPO（求和规则的分母用）。

    与 `ks_mps._q2_mpo` 同一个套路，只是把 ρ 的插入限制在 y ≤ xcut：
    有序对 (y<z) 给 2ρ_yρ_z（通道 1 里再插一个 ρ），对角 y=z 给 ρ_y²（通道 0→2）。
    """
    out = []
    for x in range(N):
        W = np.zeros((3, 2, 2, 3), dtype=float)
        rho = _mps._rho_op(x)
        W[0, :, :, 0] += _mps._I2
        W[1, :, :, 1] += _mps._I2
        W[2, :, :, 2] += _mps._I2
        if x <= xcut:
            W[0, :, :, 1] += rho
            W[1, :, :, 2] += 2.0 * rho
            W[0, :, :, 2] += rho @ rho
        out.append(W)
    return out


# ==============================================================================
# 2. 三个矩阵元 + 恒等式残差
# ==============================================================================
def field_matrix_elements(A0, A1, gap: float, t: float = 0.5, phi: float = 0.0) -> dict:
    """一次算完 ⟨1|ρ_x|0⟩、⟨1|E_x|0⟩、⟨1|j_x|0⟩（含跨切口那条）。

    返回 {"N","rho","E","j","j_seam","echo"}；振幅已按两端归一。
    `echo` = ⟨1|0⟩ 的模（正交 DMRG 应 ≈ 0，给一个直接的判据）。
    """
    N = len(A0)
    nrm = np.sqrt(_mps_norm(A0) * _mps_norm(A1))
    rho = trans_amp_site(A1, A0, [_mps._rho_op(x) for x in range(N)]) / nrm
    E = np.cumsum(rho)
    jl = trans_amp_link(A1, A0, [link_current_op(t)] * max(N - 1, 0)) / nrm
    js = trans_amp_mpo(A1, seam_current_mpo(N, t, phi), A0) / nrm
    j = np.concatenate([jl, [js]]) if N > 1 else np.array([js])
    return {"N": N, "rho": rho, "E": E, "j": j, "j_seam": js,
            "echo": float(np.abs(trans_amp_mpo(A1, [_id_mpo(N)[0]] * N, A0) / nrm))}


def _id_mpo(N):
    """单位 MPO（D=1），只为算 ⟨1|0⟩。"""
    W = np.zeros((1, 2, 2, 1), dtype=float)
    W[0, :, :, 0] = _mps._I2
    return [W] * N


def eom_residual(fe, gap: float) -> dict:
    """R_x = ⟨1|j_x|0⟩ + i·gap·⟨1|E_x|0⟩ 的 x 散布（恒等式要求它是常数）。

    返回 {"c": 常数（= ⟨1|j_{N−1}|0⟩ 的估计）, "spread": max|R−mean|,
    "rel": spread/|mean|}。rel 同时度量"|1⟩ 是否真的是本征态"。
    """
    R = np.asarray(fe["j"]) + 1j * gap * np.asarray(fe["E"])
    c = complex(np.mean(R))
    spread = float(np.abs(R - c).max())
    return {"c": c, "spread": spread, "rel": spread / max(abs(c), 1e-300),
            "R": R}


